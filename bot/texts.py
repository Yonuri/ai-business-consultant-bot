USER_PROMPT_TEMPLATE = (
    "КОНТЕКСТ ИЗ БАЗЫ ЗНАНИЙ:\n"
    "{context}\n\n"
    "---\n"
    "ВОПРОС КЛИЕНТА: {question}\n\n"
    "Ответь на вопрос строго по контексту выше. "
    "Если ответа в контексте нет — верни {no_answer_token}."
)


def user_prompt(context: str, question: str) -> str:
    return USER_PROMPT_TEMPLATE.format(
        context=context,
        question=question,
        no_answer_token=NO_ANSWER_TOKEN,
    )
